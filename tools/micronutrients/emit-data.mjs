/*
 * Turns tools/micronutrients/usda-mapping.json into src/domain/micronutrient-data.ts.
 *
 *   node tools/micronutrients/emit-data.mjs
 *
 * The mapping is the reviewable artifact; this file is only the compact form the app ships.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const ORDER = ['iron', 'calcium', 'magnesium', 'zinc', 'potassium', 'sodium', 'iodine', 'vitaminD', 'vitaminB12', 'folate', 'vitaminC']
const IN = new URL('./usda-mapping.json', import.meta.url)
const OUT = new URL('../../src/domain/micronutrient-data.ts', import.meta.url)

const mapping = JSON.parse(readFileSync(IN, 'utf8'))
const ids = Object.keys(mapping).sort()

const round = (v) => (v >= 100 ? Math.round(v) : Math.round(v * 100) / 100)
const rows = ids.map((id) => {
  const v = mapping[id].values ?? {}
  const cells = ORDER.map((k) => (v[k] === undefined ? 'n' : String(round(v[k]))))
  return `  ${/^[a-z][a-z0-9]*$/.test(id) ? id : `'${id}'`}: [${cells.join(', ')}], // ${mapping[id].usda}`
})

const file = `/*
 * Micronutrients per 100 g, generated by tools/micronutrients/emit-data.mjs. Do not edit by hand.
 *
 * Source: USDA FoodData Central (SR Legacy, Foundation Foods), public domain under CC0 1.0.
 * Which USDA entry stands behind which food, and how far its macros are from the ones in
 * foods.ts, is recorded in tools/micronutrients/usda-mapping.json. \`n\` means the source has no
 * value for that nutrient, which is not the same as zero - see micronutrients.ts.
 *
 * ${ids.length} of the built-in foods are covered. The rest, and the Vietnamese prepared dishes
 * above all, have no entry yet and show as "no data" in the app.
 */
import { MICRO_IDS, type Micros } from './micronutrients'

/** ${ORDER.join(', ')} */
type Row = (number | null)[]
const n = null

const ROWS: Record<string, Row> = {
${rows.join('\n')}
}

/** USDA id per food, so the app can say where a number comes from. */
export const MICRO_FDC_ID: Record<string, number> = {
${ids.map((id) => `  ${/^[a-z][a-z0-9]*$/.test(id) ? id : `'${id}'`}: ${mapping[id].fdcId},`).join('\n')}
}

export const MICROS_PER_100G: Record<string, Micros> = Object.fromEntries(
  Object.entries(ROWS).map(([id, row]) => [
    id,
    Object.fromEntries(MICRO_IDS.map((key, i) => [key, row[i]]).filter(([, v]) => v !== null)) as Micros,
  ]),
)
`

writeFileSync(OUT, file)
console.log(`${ids.length} Lebensmittel nach src/domain/micronutrient-data.ts geschrieben`)
